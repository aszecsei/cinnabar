using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace Cinnabar.Editor.Link.Generator;

/// <summary>
/// Writes the C# for a link schema: an enum for each enum, a record for each struct and message with its reader and
/// writer, and the dispatch from message kind to reader, in the link's namespace. Names go from Odin's Snake_Case to
/// PascalCase.
/// </summary>
public static class SchemaCode
{
    public const string Namespace = "Cinnabar.Editor.Link.Protocol";

    public static string Generate(string json, string ns = Namespace, string messagesClass = "LinkMessages")
    {
        var root = (Dictionary<string, object>)Json.Parse(json);
        var version = ulong.Parse((string)root["version"], NumberStyles.HexNumber, CultureInfo.InvariantCulture);
        var enums = ((List<object>)root["enums"]).Cast<Dictionary<string, object>>().ToList();
        var enumBases = enums.ToDictionary(e => (string)e["name"], e => (string)e["type"]);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> from a link's schema by Cinnabar.Editor.Link.Generator.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        foreach (var e in enums)
        {
            sb.AppendLine($"public enum {Pascal((string)e["name"])} : {Primitive((string)e["type"]).CSharp}");
            sb.AppendLine("{");
            foreach (var value in ((List<object>)e["values"]).Cast<Dictionary<string, object>>())
            {
                sb.AppendLine($"    {Pascal((string)value["name"])} = {(long)value["value"]},");
            }
            sb.AppendLine("}");
            sb.AppendLine();
        }
        foreach (var s in ((List<object>)root["structs"]).Cast<Dictionary<string, object>>())
        {
            WriteRecord(sb, s, kind: null, enumBases);
        }
        var messages = ((List<object>)root["messages"]).Cast<Dictionary<string, object>>().ToList();
        foreach (var m in messages)
        {
            WriteRecord(sb, m, kind: (long)m["kind"], enumBases);
        }

        sb.AppendLine($"public static class {messagesClass}");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>The schema's version. The other end refuses an editor with another one.</summary>");
        sb.AppendLine($"    public const ulong ProtocolVersion = 0x{version:x16}UL;");
        sb.AppendLine();
        sb.AppendLine("    public static global::Cinnabar.Editor.Link.ILinkMessage Read(ushort kind, ref global::Cinnabar.Editor.Link.LinkReader reader) => kind switch");
        sb.AppendLine("    {");
        foreach (var m in messages)
        {
            sb.AppendLine($"        {(long)m["kind"]} => {Pascal((string)m["name"])}.Read(ref reader),");
        }
        sb.AppendLine("        _ => throw new global::Cinnabar.Editor.Link.LinkProtocolException($\"unknown message kind {kind}\"),");
        sb.AppendLine("    };");
        sb.AppendLine("}");
        return sb.ToString();
    }

    static void WriteRecord(StringBuilder sb, Dictionary<string, object> type, long? kind, Dictionary<string, string> enums)
    {
        var name = Pascal((string)type["name"]);
        var fields = ((List<object>)type["fields"]).Cast<Dictionary<string, object>>()
            .Select(f => (Name: Pascal((string)f["name"]), Local: "@" + (string)f["name"], Type: (string)f["type"]))
            .ToList();
        foreach (var f in fields.Where(f => f.Name == name || f.Name == "MessageKind"))
        {
            throw new FormatException($"{type["name"]} has a field {f.Name}, which C# cannot have in a type named {name}");
        }
        var parameters = string.Join(", ", fields.Select(f => $"{CSharpType(f.Type, enums)} {f.Name}"));
        var interfaces = kind == null ? "" : " : global::Cinnabar.Editor.Link.ILinkMessage";
        sb.AppendLine($"public sealed partial record {name}({parameters}){interfaces}");
        sb.AppendLine("{");
        if (kind != null)
        {
            sb.AppendLine($"    public const ushort KindId = {kind};");
            sb.AppendLine();
            sb.AppendLine("    public ushort MessageKind => KindId;");
            sb.AppendLine();
        }
        sb.AppendLine("    public void Write(global::Cinnabar.Editor.Link.LinkWriter writer)");
        sb.AppendLine("    {");
        foreach (var f in fields)
        {
            sb.AppendLine($"        {WriteExpression(f.Type, f.Name, "writer", enums, 0)};");
        }
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine($"    public static {name} Read(ref global::Cinnabar.Editor.Link.LinkReader reader)");
        sb.AppendLine("    {");
        foreach (var f in fields)
        {
            sb.AppendLine($"        var {f.Local} = {ReadExpression(f.Type, "reader", enums, 0)};");
        }
        sb.AppendLine($"        return new {name}({string.Join(", ", fields.Select(f => f.Local))});");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    static string CSharpType(string type, Dictionary<string, string> enums)
    {
        if (TryArray(type, out var count, out var elem))
        {
            return CSharpType(elem, enums) + "[]";
        }
        if (IsPrimitive(type))
        {
            return Primitive(type).CSharp;
        }
        return Pascal(type);
    }

    static string ReadExpression(string type, string reader, Dictionary<string, string> enums, int depth)
    {
        // Bytes, such as a component's memory, are copied at once instead of one element at a time.
        if (type == "[]u8")
        {
            return $"{reader}.ReadBytes()";
        }
        if (TryArray(type, out var count, out var elem))
        {
            var r = $"r{depth}";
            var element = $"static (ref global::Cinnabar.Editor.Link.LinkReader {r}) => {ReadExpression(elem, r, enums, depth + 1)}";
            return count == null ? $"{reader}.ReadSlice({element})" : $"{reader}.ReadFixed({count}, {element})";
        }
        if (IsPrimitive(type))
        {
            return $"{reader}.Read{Primitive(type).Method}()";
        }
        if (enums.TryGetValue(type, out var underlying))
        {
            return $"({Pascal(type)}){reader}.Read{Primitive(underlying).Method}()";
        }
        return $"{Pascal(type)}.Read(ref {reader})";
    }

    static string WriteExpression(string type, string value, string writer, Dictionary<string, string> enums, int depth)
    {
        if (type == "[]u8")
        {
            return $"{writer}.WriteBytes({value})";
        }
        if (TryArray(type, out var count, out var elem))
        {
            var w = $"w{depth}";
            var e = $"e{depth}";
            var element = $"static ({w}, {e}) => {WriteExpression(elem, e, w, enums, depth + 1)}";
            return count == null ? $"{writer}.WriteSlice({value}, {element})" : $"{writer}.WriteFixed({value}, {count}, {element})";
        }
        if (IsPrimitive(type))
        {
            return $"{writer}.Write{Primitive(type).Method}({value})";
        }
        if (enums.TryGetValue(type, out var underlying))
        {
            return $"{writer}.Write{Primitive(underlying).Method}(({Primitive(underlying).CSharp}){value})";
        }
        return $"{value}.Write({writer})";
    }

    // [N]T is a fixed array and []T a slice.
    static bool TryArray(string type, out int? count, out string elem)
    {
        count = null;
        elem = "";
        if (!type.StartsWith("[", StringComparison.Ordinal))
        {
            return false;
        }
        var close = type.IndexOf(']');
        if (close > 1)
        {
            count = int.Parse(type.Substring(1, close - 1), CultureInfo.InvariantCulture);
        }
        elem = type.Substring(close + 1);
        return true;
    }

    static readonly Dictionary<string, (string CSharp, string Method)> Primitives = new()
    {
        ["u8"] = ("byte", "U8"),
        ["u16"] = ("ushort", "U16"),
        ["u32"] = ("uint", "U32"),
        ["u64"] = ("ulong", "U64"),
        ["i8"] = ("sbyte", "I8"),
        ["i16"] = ("short", "I16"),
        ["i32"] = ("int", "I32"),
        ["i64"] = ("long", "I64"),
        ["f32"] = ("float", "F32"),
        ["f64"] = ("double", "F64"),
        ["bool"] = ("bool", "Bool"),
        ["string"] = ("string", "String"),
    };

    static bool IsPrimitive(string type) => Primitives.ContainsKey(type);

    static (string CSharp, string Method) Primitive(string type) =>
        Primitives.TryGetValue(type, out var p) ? p : throw new FormatException($"unknown type {type}");

    /// <summary><c>Frame_Target</c> and <c>layout_hash</c> become <c>FrameTarget</c> and <c>LayoutHash</c>.</summary>
    public static string Pascal(string name) =>
        string.Concat(name.Split(['_'], StringSplitOptions.RemoveEmptyEntries)
            .Select(part => char.ToUpperInvariant(part[0]) + part.Substring(1)));
}
